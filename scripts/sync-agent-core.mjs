#!/usr/bin/env node
// =============================================================================
// Sync / verify the vendored agent-core.
// =============================================================================
// agent-core is the agent loop every Redstart host runs (chat-ui, the agent
// bench, Nest's task runner, and Yellowscript). It lives in redstart-project at
// shared/agent-core/. Yellowscript is a separate repo, so the directory is
// copied here verbatim, pinned to a commit, and NEVER edited in place: a fix
// goes to redstart-project and comes back with the next sync.
//
//   node scripts/sync-agent-core.mjs <path-to-redstart-project> [git-ref]
//       Copy shared/agent-core/ at <git-ref> (default: HEAD of that checkout)
//       into src/vendor/agent-core/ and record the commit and file hashes.
//
//   node scripts/sync-agent-core.mjs --check
//       Fail if any vendored file differs from the hashes recorded at sync
//       time (an edit made here instead of upstream). Run by `npm run check`.
//
// Why not an npm package: npm cannot install a subdirectory of a git repo, and
// GitHub Packages needs an auth token for every install, public or not. A
// pinned copy with an integrity check gives the same guarantee — one version
// of the loop, changed in one place — with nothing to authenticate.
// =============================================================================

import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DEST = join(ROOT, 'src', 'vendor', 'agent-core')
const MANIFEST = join(DEST, 'VENDORED.json')
const UPSTREAM_DIR = 'shared/agent-core'
// Only what Yellowscript can run: the loop's modules and their types. The
// host-globals file types the core for Nest's own no-DOM check and is not
// needed here.
const INCLUDE = (name) => (name.endsWith('.mjs') || name === 'types.d.ts') && !name.endsWith('.test.mjs')

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex')

function check() {
  let manifest
  try {
    manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
  } catch {
    console.error(`agent-core: ${MANIFEST} is missing. Run the sync first.`)
    process.exit(1)
  }
  const problems = []
  const onDisk = readdirSync(DEST).filter(INCLUDE)
  for (const name of onDisk) {
    if (!(name in manifest.files)) problems.push(`${name}: not from upstream (added here)`)
  }
  for (const [name, hash] of Object.entries(manifest.files)) {
    let actual
    try {
      actual = sha256(readFileSync(join(DEST, name)))
    } catch {
      problems.push(`${name}: missing`)
      continue
    }
    if (actual !== hash) problems.push(`${name}: edited since the sync`)
  }
  if (problems.length > 0) {
    console.error('agent-core: the vendored copy does not match upstream commit ' + manifest.commit)
    for (const p of problems) console.error('  - ' + p)
    console.error('Make the change in redstart-project shared/agent-core/, then re-sync.')
    process.exit(1)
  }
  console.log(`agent-core: ${Object.keys(manifest.files).length} files match ${manifest.commit.slice(0, 7)}`)
}

function sync(repo, ref) {
  const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' }).trim()
  const commit = git('rev-parse', `${ref}^{commit}`)
  const names = git('ls-tree', '--name-only', `${commit}:${UPSTREAM_DIR}`).split('\n').filter(INCLUDE)
  if (names.length === 0) throw new Error(`no agent-core files at ${commit}:${UPSTREAM_DIR}`)

  rmSync(DEST, { recursive: true, force: true })
  mkdirSync(DEST, { recursive: true })
  const files = {}
  for (const name of names.sort()) {
    const buf = execFileSync('git', ['-C', repo, 'show', `${commit}:${UPSTREAM_DIR}/${name}`])
    writeFileSync(join(DEST, name), buf)
    files[name] = sha256(buf)
  }
  const manifest = {
    upstream: 'https://github.com/ImDeadWeight/redstart-project',
    path: UPSTREAM_DIR,
    commit,
    subject: git('log', '-1', '--format=%s', commit),
    syncedAt: new Date().toISOString().slice(0, 10),
    note: 'Generated by scripts/sync-agent-core.mjs. Do not edit these files here; change them upstream and re-sync.',
    files,
  }
  writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n')
  console.log(`agent-core: synced ${names.length} files from ${commit.slice(0, 7)} (${manifest.subject})`)
}

const [arg, ref] = process.argv.slice(2)
if (arg === '--check') check()
else if (arg) sync(arg, ref ?? 'HEAD')
else {
  console.error('usage: sync-agent-core.mjs <path-to-redstart-project> [git-ref] | --check')
  process.exit(2)
}
